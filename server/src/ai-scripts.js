const SCENE_ALIASES = [
  [/体验|新客|初次|第一次|首次|破冰|成交|促单/, 'trial'],
  [/过期|到期|续卡|续课|快用完|课时不足|剩余/, 'expiring'],
  [/沉睡|没来|未到店|不来|激活|召回|流失|好久/, 'inactive'],
  [/课后|反馈|总结/, 'after_class'],
  [/生日|祝福/, 'birthday'],
];
function sceneOf(text) {
  const t = String(text || '');
  if (SCENES[t]) return t;
  const hit = SCENE_ALIASES.find(([re]) => re.test(t));
  return hit ? hit[1] : '';
}

module.exports = { SCENES, sceneOf };
